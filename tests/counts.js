// Archive routes test. Run: node tests/archive.js  (Node 22+; dummy secrets only; in-memory SQLite built from worker/schema.sql)
const fs=require('fs');const {make,DatabaseSync}=require('./dbshim');
let fails=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fails++;};
const CODE='test-code-'+Math.random().toString(36).slice(2),ADMIN='test-admin-'+Math.random().toString(36).slice(2);
(async()=>{
  const W=(await import('data:text/javascript;base64,'+Buffer.from(fs.readFileSync('worker/worker.js','utf8')).toString('base64'))).default;
  const raw=new DatabaseSync(':memory:');raw.exec(fs.readFileSync('worker/schema.sql','utf8'));
  const cols=raw.prepare("PRAGMA table_info(roadmap_features)").all().filter(c=>c.notnull&&c.dflt_value===null&&!c.pk).map(c=>c.name);
  raw.prepare('INSERT INTO roadmap_features (id'+cols.map(c=>','+c).join('')+') VALUES (?'+cols.map(()=>',?').join('')+')').run('F-001',...cols.map(()=>'x'));
  const env={DB:make(raw),ROADMAP_CODE:CODE,ROADMAP_ADMIN:ADMIN};
  const call=async(method,path,{body,gate,admin}={})=>{const h={Origin:'https://jgoldatl.github.io'};if(gate)h['X-Gate-Token']=gate;if(admin)h['X-Admin-Token']=admin;
    const r=await W.fetch(new Request('https://x'+path,{method,headers:h,body:body===undefined?undefined:JSON.stringify(body)}),env);let d={};try{d=await r.json();}catch(x){}return {s:r.status,d};};
  const T=(await call('POST','/gate',{body:{page:'roadmap',code:CODE}})).d.token;
  const A=(await call('POST','/admin',{gate:T,body:{code:ADMIN}})).d.admin_token;
  ok(!!T&&!!A,'gate and admin tokens issued');
  const mk=async(n)=>{for(let i=0;i<n;i++)await call('POST','/roadmap/comment',{gate:T,body:{feature_id:'F-001',name:'A',comment:'comment number '+i}});};
  ok((await call('GET','/roadmap/counts',{gate:T})).s===403,'counts refused without the admin token (403)');
  ok((await call('POST','/roadmap/seen',{gate:T,body:{kinds:['comment']}})).s===403,'seen refused without the admin token (403)');
  await mk(3);
  await call('POST','/roadmap/suggest',{gate:T,body:{name:'A',feature:'Test feature',accomplishes:'Test accomplishes',about:'',vision:''}});
  raw.exec("INSERT INTO feedback (visit_id,topic,message) VALUES ('v1','Idea','m1'),('v2','Problem','m2')");
  let c=(await call('GET','/roadmap/counts',{gate:T,admin:A})).d;
  ok(c.comment.fresh===3&&c.comment.total===3&&c.suggestion.fresh===1&&c.feedback.fresh===2&&c.feedback.total===2,'first look: everything is new '+JSON.stringify(c));
  ok((await call('POST','/roadmap/seen',{gate:T,admin:A,body:{kinds:['comment']}})).s===200,'opening the comments list marks it seen');
  c=(await call('GET','/roadmap/counts',{gate:T,admin:A})).d;
  ok(c.comment.fresh===0&&c.comment.total===3,'comments now 0/3');
  ok(c.feedback.fresh===2&&c.suggestion.fresh===1,'other lists keep their own new counts');
  await mk(2);
  c=(await call('GET','/roadmap/counts',{gate:T,admin:A})).d;
  ok(c.comment.fresh===2&&c.comment.total===5,'two more arrive: 2/5');
  ok((await call('POST','/roadmap/archive',{gate:T,admin:A,body:{kind:'comment',id:5,archived:1}})).s===200,'archive the newest comment');
  c=(await call('GET','/roadmap/counts',{gate:T,admin:A})).d;
  ok(c.comment.fresh===1&&c.comment.total===4,'archived items leave both numbers: 1/4');
  ok((await call('POST','/roadmap/seen',{gate:T,admin:A,body:{kinds:['feedback','suggestion']}})).s===200,'two lists marked at once');
  c=(await call('GET','/roadmap/counts',{gate:T,admin:A})).d;
  ok(c.feedback.fresh===0&&c.feedback.total===2&&c.suggestion.fresh===0&&c.suggestion.total===1,'feedback 0/2, suggestions 0/1');
  ok((await call('POST','/roadmap/seen',{gate:T,admin:A,body:{kinds:['visits']}})).s===400,'unknown kind refused (400)');
  ok((await call('POST','/roadmap/seen',{gate:T,admin:A,body:{kinds:[]}})).s===400,'empty list refused (400)');
  ok((await call('POST','/roadmap/seen',{gate:T,admin:A,body:{kinds:["comment'; DROP TABLE roadmap_comments;--"]}})).s===400&&raw.prepare('SELECT COUNT(*) n FROM roadmap_comments').get().n===5,'injection attempt refused, table intact');
  raw.exec('DROP TABLE admin_seen');
  ok((await call('GET','/roadmap/counts',{gate:T,admin:A})).s===200,'works even if the admin_seen table was never created (made on first use)');
  console.log(fails?fails+' FAILED':'all passed');process.exit(fails?1:0);
})();
